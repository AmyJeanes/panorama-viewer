"""Draws the example library: tours of test-pattern panoramas whose labels give world directions, cut into tiles by tiles.py, with thumbnails by thumbs.py.

    uv run examples/make.py

Every image is labelled in world directions (its heading applied), so with correct headings the labels agree from every
panorama, and each link's arrow should sit on that panorama's "to <panorama>" floor label.
"""
import json
import math
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).parent
SOURCE = HERE / 'test-patterns'
COMPASS = ['N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW']


def draw(path, title, colour, heading=0, width=4096, links=(), gap=None, band=None):
    w, h = width, width // 2
    img = Image.new('RGB', (w, h))
    d = ImageDraw.Draw(img)
    # Sky to floor, in the panorama's colour
    for row in range(h):
        t = row / h
        d.line([(0, row), (w, row)], fill=tuple(int(c * (1.1 - t * 0.8)) for c in colour))

    # Where a world yaw and a pitch fall in the image
    def x(world):
        return ((world - heading) / 360 + 0.5) % 1 * w

    def y(pitch):
        return (0.5 - pitch / 180) * h

    for yaw in range(0, 360, 15):
        d.line([(x(yaw), 0), (x(yaw), h)], fill=(255, 255, 255) if yaw % 45 == 0 else (160, 160, 160), width=max(1, w // 1024 * (2 if yaw % 45 == 0 else 1)))
    for pitch in range(-75, 90, 15):
        d.line([(0, y(pitch)), (w, y(pitch))], fill=(255, 255, 255) if pitch == 0 else (160, 160, 160), width=max(1, w // 1024 * (3 if pitch == 0 else 1)))
    big = ImageFont.load_default(w // 40)
    small = ImageFont.load_default(w // 70)
    for i, name in enumerate(COMPASS):
        d.text((x(i * 45), y(6)), f'{name} {i * 45}°', font=big, fill='white', anchor='ms')
        d.text((x(i * 45 + 22.5), y(20)), title, font=small, fill='white', anchor='mm')
    for to, yaw in links:
        d.text((x(yaw), y(-16)), f'to {to}', font=big, fill=(255, 230, 0), anchor='mm')
    if gap:  # missing source tiles, left black
        d.rectangle([x(gap[0]), y(gap[3]), x(gap[1]), y(gap[2])], fill='black')
    if band:  # only a band around the horizon survives
        d.rectangle([0, 0, w, y(band[1])], fill='black')
        d.rectangle([0, y(band[0]), w, h], fill='black')
    img.save(path, quality=92)


def tiles(original, out):
    r = subprocess.run([sys.executable, '-I', str(HERE.parent / 'tiles.py'), str(original), str(out)], stdout=subprocess.PIPE, text=True, check=True)
    return json.loads(r.stdout)


def tour(file, title, panoramas, start=None):
    m = {'id': f'example-{Path(file).stem}', 'title': title,
         'source': {'name': 'Generated by examples/make.py'}, 'credits': [{'role': 'Test patterns', 'name': 'examples/make.py'}],
         'headingReference': 'aligned', 'start': start or panoramas[0]['id'], 'panoramas': panoramas}
    (SOURCE / file).write_text(json.dumps(m, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    subprocess.run([sys.executable, '-I', str(HERE.parent / 'thumbs.py'), str(SOURCE / file)], stdout=subprocess.DEVNULL, check=True)
    return {'name': title, 'path': f'test-patterns/{file}'}


def panorama(tmp, id, title, colour, heading=0, width=4096, links=(), **fields):
    original = tmp / f'{id}.jpg'
    draw(original, title, colour, heading, width, links, fields.pop('gap', None), fields.get('verticalRange'))
    return {'id': id, 'title': title, **tiles(original, SOURCE), 'heading': heading,
            **({'links': [{'to': to, 'yaw': yaw} for to, yaw in links]} if links else {}), **fields}


def main():
    # The output is wholly generated, so start clean rather than leave tiles of an older layout behind
    shutil.rmtree(SOURCE, ignore_errors=True)
    SOURCE.mkdir()
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        # A square of four rooms, 3 m apart; headings differ so a wrong one shows as disagreeing labels
        corners = {'a': (0, 0, 0, (200, 70, 70)), 'b': (3, 0, 90, (70, 160, 70)), 'c': (3, 3, 200, (70, 90, 200)), 'd': (0, 3, 315, (170, 120, 40))}

        # Compass bearing from one room to another, -180 to 180
        def bearing(p, q):
            return round((math.degrees(math.atan2(q[0] - p[0], q[1] - p[1])) + 180) % 360 - 180, 2)

        rooms = []
        for id, (px, py, heading, colour) in corners.items():
            links = [(o, bearing((px, py), corners[o][:2])) for o in corners if o != id]
            # The first room is larger, so its tiles have more than one level
            rooms.append(panorama(tmp, id, f'Room {id.upper()}', colour, heading, 8192 if id == 'a' else 4096, links))
        # The tour starts in a room other than the first, at its own start view
        rooms[1]['startView'] = {'yaw': 45, 'pitch': -10}
        thumbs = [panorama(tmp, f'thumb-{i}', f'Thumbnail {i}', c) for i, c in enumerate([(160, 60, 120), (60, 120, 160), (120, 160, 60)], 1)]
        # A start view without a yaw faces the panorama's heading
        thumbs[1]['startView'] = {'pitch': -20}
        entries = [
            tour('linked-tour.json', 'Linked tour', rooms, start='b'),
            tour('single.json', 'Single panorama', [panorama(tmp, 'single', 'Single', (120, 80, 160))]),
            tour('incomplete.json', 'Incomplete panorama', [panorama(tmp, 'incomplete', 'Incomplete', (60, 140, 140), gap=(30, 150, -20, 45), partial=True, coverage=0.75)]),
            tour('low-resolution.json', 'Low resolution', [panorama(tmp, 'low-resolution', 'Low resolution', (150, 150, 60), width=1024, partial='Low Resolution')]),
            tour('horizon-band.json', 'Horizon band only', [panorama(tmp, 'horizon-band', 'Horizon band', (90, 90, 150), verticalRange=[-30, 30])]),
            tour('thumbnails.json', 'Thumbnails only', thumbs),
        ]
    (HERE / 'library.json').write_text(json.dumps({'name': 'Panorama Viewer examples', 'tours': entries}, indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
